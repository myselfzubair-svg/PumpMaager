-- Supabase Schema for Pump Manager (Dynamic Product-Wise Normalization)

-- ==========================================
-- 1. CLEANUP & INITIAL SETUP
-- ==========================================
DO $$
DECLARE
    r RECORD;
BEGIN
    -- Drop old redundant/plural table names
    EXECUTE 'DROP TABLE IF EXISTS credits CASCADE';
    EXECUTE 'DROP TABLE IF EXISTS expenses CASCADE';
    EXECUTE 'DROP TABLE IF EXISTS recoveries CASCADE';
    EXECUTE 'DROP TABLE IF EXISTS credit_entries CASCADE';
    EXECUTE 'DROP TABLE IF EXISTS expense_entries CASCADE';
    EXECUTE 'DROP TABLE IF EXISTS recovery_entries CASCADE';

    -- Drop other legacy tables
    EXECUTE 'DROP TABLE IF EXISTS nozzle_readings CASCADE';
    EXECUTE 'DROP TABLE IF EXISTS ms_nozzle_readings CASCADE';
    EXECUTE 'DROP TABLE IF EXISTS hsd_nozzle_readings CASCADE';
    EXECUTE 'DROP TABLE IF EXISTS general_nozzle_readings CASCADE';
    EXECUTE 'DROP TABLE IF EXISTS audit_line_items CASCADE';
    EXECUTE 'DROP TABLE IF EXISTS daily_configs CASCADE';
    EXECUTE 'DROP TABLE IF EXISTS connection_test CASCADE';

    -- Drop dynamic nozzle tables (if any)
    FOR r IN (SELECT tablename FROM pg_tables WHERE schemaname = 'public' AND tablename LIKE 'readings_%') LOOP
        EXECUTE 'DROP TABLE IF EXISTS ' || quote_ident(r.tablename) || ' CASCADE';
    END LOOP;
END $$;

-- ==========================================
-- 2. SCHEMA-LEVEL PERMISSIONS
-- ==========================================
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON FUNCTIONS TO anon, authenticated, service_role;

-- ==========================================
-- 3. CORE TABLES (USEFUL)
-- ==========================================

CREATE TABLE IF NOT EXISTS users (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    mobile_number TEXT UNIQUE NOT NULL,
    username TEXT,
    owner_name TEXT,
    pump_name TEXT,
    role TEXT DEFAULT 'STAFF',
    password_hash TEXT,
    created_at BIGINT DEFAULT extract(epoch from now()) * 1000,
    updated_at BIGINT DEFAULT extract(epoch from now()) * 1000
);

CREATE TABLE IF NOT EXISTS memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_phone TEXT NOT NULL,
    admin_phone TEXT NOT NULL,
    pump_name TEXT,
    username TEXT,
    role TEXT,
    account_id UUID,
    created_at BIGINT DEFAULT extract(epoch from now()) * 1000,
    UNIQUE(staff_phone, admin_phone)
);

CREATE TABLE IF NOT EXISTS pumps (
    mobile_number TEXT PRIMARY KEY,
    pump_name TEXT NOT NULL,
    num_ms_nozzles INTEGER DEFAULT 0,
    ms_nozzle_labels TEXT,
    num_hsd_nozzles INTEGER DEFAULT 0,
    hsd_nozzle_labels TEXT,
    num_ms_tanks INTEGER DEFAULT 0,
    num_hsd_tanks INTEGER DEFAULT 0,
    ms_tank_labels TEXT,
    hsd_tank_labels TEXT,
    product_names TEXT,
    udhari_names TEXT,
    updated_at BIGINT DEFAULT extract(epoch from now()) * 1000
);

CREATE TABLE IF NOT EXISTS staff_members (
    phone TEXT NOT NULL,
    owner_admin_phone TEXT NOT NULL,
    name TEXT,
    password_hash TEXT,
    role TEXT,
    account_id UUID,
    PRIMARY KEY (phone, owner_admin_phone)
);

CREATE TABLE IF NOT EXISTS registered_nozzles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mobile_number TEXT NOT NULL,
    nozzle_type TEXT,
    label TEXT,
    nozzle_name TEXT,
    nozzle_number TEXT,
    nozzle_id TEXT,
    product_id TEXT,
    tank_name TEXT,
    tank_id TEXT,
    nozzle_index INTEGER,
    initial_reading DOUBLE PRECISION,
    is_active BOOLEAN DEFAULT TRUE,
    UNIQUE(mobile_number, label)
);

CREATE TABLE IF NOT EXISTS daily_sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_phone TEXT NOT NULL,
    date TEXT NOT NULL,
    product_name TEXT NOT NULL,
    product_id TEXT,
    density DOUBLE PRECISION,
    rate DOUBLE PRECISION,
    opening_stock DOUBLE PRECISION,
    entered_by TEXT,
    timestamp BIGINT DEFAULT extract(epoch from now()) * 1000,
    UNIQUE(admin_phone, date, product_name)
);

CREATE TABLE IF NOT EXISTS saved_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_admin_phone TEXT NOT NULL,
    date TEXT NOT NULL,
    ca_name TEXT,
    meter_no TEXT,
    audit_type TEXT,
    summary_text TEXT,
    html_content TEXT,
    timestamp BIGINT,
    cash_submitted DOUBLE PRECISION,
    actual_cash_collected DOUBLE PRECISION,
    report_id TEXT,
    total_fuel_sales_amount DOUBLE PRECISION,
    total_udhari_jama DOUBLE PRECISION,
    total_kharch DOUBLE PRECISION,
    total_udhar DOUBLE PRECISION,
    phone_pe_amount DOUBLE PRECISION,
    cards_amount DOUBLE PRECISION,
    expected_cash_balance DOUBLE PRECISION,
    tally_difference DOUBLE PRECISION
);

-- ==========================================
-- 4. SPECIALIZED FINANCIAL TABLES
