CREATE TABLE IF NOT EXISTS expense (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id TEXT NOT NULL,
    owner_admin_phone TEXT NOT NULL,
    description TEXT,
    category TEXT,
    amount DOUBLE PRECISION,
    date TEXT,
    timestamp BIGINT,
    ca_name TEXT,
    UNIQUE(report_id, timestamp, category, amount)
